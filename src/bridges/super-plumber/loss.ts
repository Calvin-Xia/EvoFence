import { MAPPINGS } from './mapping.js';
import type { DeliverySnapshot, LossEntry } from './types.js';

export function mappingReport(): readonly LossEntry[] { return MAPPINGS.map(row => ({ ...row })); }
export function lossesFor(delivery: DeliverySnapshot): readonly LossEntry[] {
  const sources = new Set<string>();
  for (const node of delivery.nodes) {
    sources.add(`${node.type}.status.${node.status}`);
    if (Object.hasOwn(node, 'review')) sources.add('node.review');
    if (Object.hasOwn(node, 'assigned_to')) sources.add('node.assigned_to');
  }
  for (const edge of delivery.edges) sources.add('edge.type.' + edge.type);
  if (Object.hasOwn(delivery.graph, 'review')) {
    sources.add('graph.review.status'); sources.add('graph.review.by'); sources.add('graph.review.at');
    const review = delivery.graph.review as { layers?: unknown[] };
    if (review.layers !== undefined && review.layers.length > 0) {
      for (const key of ['level', 'by', 'at']) sources.add('graph.review.layers.' + key);
    }
  }
  if (Object.hasOwn(delivery.graph, 'design_approved')) sources.add('graph.design_approved');
  return MAPPINGS.filter(row => row.classification !== 'supported' && sources.has(row.source)).map(row => ({ ...row }));
}
export interface Difference { readonly path: string; readonly before: unknown; readonly after: unknown }
/** Compare value/presence, array ordering and every field; object key order is immaterial. */
export function difference(before: unknown, after: unknown, at = '$'): readonly Difference[] {
  if (Object.is(before, after)) return [];
  if (typeof before === 'object' && before !== null && typeof after === 'object' && after !== null && Array.isArray(before) === Array.isArray(after)) {
    const a = before as Record<string, unknown>, b = after as Record<string, unknown>;
    const keys = [...new Set([...Object.keys(a), ...Object.keys(b)])].sort();
    const result: Difference[] = [];
    for (const key of keys) {
      if (!Object.hasOwn(a, key) || !Object.hasOwn(b, key)) result.push({ path: at + '.' + key, before: a[key], after: b[key] });
      else result.push(...difference(a[key], b[key], at + '.' + key));
    }
    if (Array.isArray(before) && Array.isArray(after) && before.length !== after.length && result.length === 0) {
      result.push({ path: at + '.length', before: before.length, after: after.length });
    }
    return result;
  }
  return [{ path: at, before, after }];
}
