    'iterates stays documentary; fallback requires explicit runtime bounds/predicate and does not order; review never grants authority.', '',
    'Evidence: native-fixture. Native multi-graph SP exports, provider-live behavior and OS/host activation remain unknown.',
    'Controlled capability uplift: inconclusive; l4_capability_trial attempt 1 failed; 747 / 943 USD remain unresolved; preregistered envelope 938.470100 USD.',
